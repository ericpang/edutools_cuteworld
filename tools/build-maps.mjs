// Regenerates assets/maps/*.svg and js/maps.js from tools/maps/*.mjs: `npm run build:maps`.
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { jungle } from './maps/jungle.mjs';
import { school } from './maps/school.mjs';
import { shopping } from './maps/shopping.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));

export function buildAll() {
  const levels = [school(), jungle(), shopping()];
  const files = new Map();
  for (const L of levels) files.set(`assets/maps/${L.id}.svg`, L.svg());
  files.set('js/maps.js', mapsModule(levels));
  return files;
}

const obj = (o) => `{ ${Object.entries(o).map(([k, v]) => `${k}: ${v}`).join(', ')} }`;
const list = (items) => (items.length ? `[\n${items.map((o) => `      ${obj(o)},`).join('\n')}\n    ]` : '[]');

function mapsModule(levels) {
  const entries = levels.map((L) => {
    const d = L.data();
    return [
      `  ${d.id}: {`,
      `    id: '${d.id}',`,
      `    label: '${d.label}',`,
      `    emoji: '${d.emoji}',`,
      `    src: '${d.src}',`,
      `    spawns: ${list(d.spawns)},`,
      `    rects: ${list(d.rects)},`,
      `    circles: ${list(d.circles)},`,
      '  },',
    ].join('\n');
  });
  return [
    '// Generated by tools/build-maps.mjs from tools/maps/*.mjs. Edit those and run `npm run build:maps`, not this file.',
    '// Rects are { x, y, w, h } and circles { x, y, r } in map units; avatars cannot enter them.',
    'export const MAPS = {',
    ...entries,
    '};',
    '',
    'export const MAP_IDS = Object.keys(MAPS);',
    '',
  ].join('\n');
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  for (const [path, text] of buildAll()) {
    const file = join(root, path);
    await mkdir(dirname(file), { recursive: true });
    await writeFile(file, text);
    console.log(`wrote ${path} (${(text.length / 1024).toFixed(1)} KB)`);
  }
}
